#!/usr/bin/env python3
"""Generate LemonadepPcie0Phy.h: PCIe RC0's PHY init sequence.

Source: the vendor DT, LineageOS/android_kernel_oneplus_sm8350 @ 187d13c,
(SM8350 v2.1, which this phone is: lahaina-v2.1.dtsi overrides the base)
arch/arm64/boot/dts/vendor/qcom/lahaina-v2.1.dtsi, &pcie0 override of
(qcom,pcie@1c00000) property qcom,phy-sequence: <offset value delay_us>
triplets, which the vendor driver (drivers/pci/controller/pci-msm.c,
pcie_phy_init) writes in order to the PHY window.

  gen-pcie0-phy.py VENDOR_DTSI [LIVE_DTS]

With LIVE_DTS (dtc -I dtb -O dts of the phone's /sys/firmware/fdt), the
sequence is also checked to be identical to what the real phone's DT
carries; any difference is an error. The live dump itself stays out of git.
"""
import os
import re
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'LemonadepPcie0Phy.h')


def sequence(text):
    # Either the node itself (live dts) or a chip-revision override (&pcie0 {...}).
    m = (re.search(r'qcom,pcie@1c00000\s*\{(.*?)\n\t\t?\};', text, re.S) or
         re.search(r'&pcie0\s*\{(.*?)\n\};', text, re.S))
    body = m.group(1)
    seq = re.search(r'qcom,phy-sequence\s*=\s*<([^>]*)>', body, re.S).group(1)
    vals = [int(x, 0) for x in seq.split()]
    assert len(vals) % 3 == 0, 'phy-sequence is not (offset, value, delay) triplets'
    return [tuple(vals[i:i + 3]) for i in range(0, len(vals), 3)]


vendor = sequence(open(sys.argv[1], encoding='utf-8').read())
if len(sys.argv) > 2:
    live = sequence(open(sys.argv[2], encoding='utf-8', errors='replace').read())
    if live != vendor:
        sys.exit(f'live DT phy-sequence differs from the vendor dtsi ({len(live)} vs {len(vendor)} entries)')
    print(f'live DT matches the vendor dtsi: {len(vendor)} entries')

rows = ''.join(f'\t{{0x{o:04x}u, 0x{v:02x}u, {d}u}},\n' for o, v, d in vendor)
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write(f'''/* SPDX-License-Identifier: MIT */
/* Generated by gen-pcie0-phy.py -- do not edit. */
#ifndef LEMONADEP_PCIE0_PHY_H
#define LEMONADEP_PCIE0_PHY_H
#include <stdint.h>
/*
 * PCIe RC0 PHY init sequence, {{offset into the PHY window, value, delay_us}}.
 * Vendor DT lahaina-v2.1.dtsi &pcie0 qcom,phy-sequence (LineageOS
 * android_kernel_oneplus_sm8350 @ 187d13c), verified identical to the live
 * phone's DT. The first entry (0x240 = qcom,phy-power-down-offset) powers
 * the PHY up; pci-msm.c pcie_phy_init() writes them in this order.
 */
struct LemonadepPcie0PhyWrite {{ uint32_t offset, value, delay_us; }};
static const struct LemonadepPcie0PhyWrite LemonadepPcie0PhySequence[{len(vendor)}] = {{
{rows}}};
#endif
''')
print(f'{OUT}: {len(vendor)} writes')
